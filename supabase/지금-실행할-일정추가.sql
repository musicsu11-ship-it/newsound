-- ============================================================================
--  새소리단 — 일정 게시판에 두 캠페인 일정 넣기
--
--  ▷ 넣는 일정은 네 건입니다. (새로 넣기만 합니다. 지우거나 고치지 않습니다)
--
--     11. 16.(월)  「세대가 함께 그리는 조직문화」 밸런스게임 시작
--     11. 23.(월)  출근룩 사진 콘테스트 시작
--     11. 26.(목)  「세대가 함께 그리는 조직문화」 밸런스게임 마감
--     11. 30.(월)  출근룩 사진 콘테스트 마감
--
--  ★ 이 파일에는 지우는 문장이 하나도 없습니다.
--     delete · truncate · drop table 이 한 줄도 들어 있지 않습니다.
--     밸런스게임 투표 표(polls 등)도 전혀 건드리지 않습니다. events 표에만
--     줄을 더합니다.
--
--  ★ 여러 번 실행해도 안전합니다.
--     같은 날짜 + 같은 제목의 일정이 이미 있으면 건너뜁니다. 두 번 눌러도
--     일정이 두 개로 늘어나지 않습니다.
--
--  ▷ 하는 방법
--     ① Supabase → 왼쪽 메뉴 'SQL Editor' → 'New query'
--     ② 이 파일 전체를 복사해서 붙여넣기 (Ctrl+A → Ctrl+C → 붙여넣기)
--     ③ 오른쪽 아래 'Run' 단추 (또는 Ctrl+Enter)
--     ④ 맨 아래에 일정 네 줄이 표로 나오면 다 된 것입니다
--
--  ▷ 잘 됐는지 확인하는 방법
--     홈페이지 → 일정 → 11월 달력에서 16·23·26·30일을 눌러 보세요.
--
--  ▷ 글줄 나누기에 대하여
--     상세 내용의 줄바꿈은 chr(10) 으로 넣습니다. chr(10) 은 '엔터 한 번'을
--     뜻하는 데이터베이스 표준 표현입니다.
--
--  ▷ 등록자 이름에 대하여
--     일정에는 '누가 등록했는지'가 반드시 들어가야 합니다(DB 규칙).
--     그래서 관리자 계정을 한 분 찾아 그분 이름으로 넣습니다.
--     관리자가 없으면 간사, 그래도 없으면 단원 순으로 찾습니다.
--     나중에 일정을 누르면 나오는 '수정' 단추로 언제든 고치실 수 있습니다.
-- ============================================================================

do $$
declare
  owner_id   uuid;
  owner_name text;
  added      int;
begin
  -- ── 등록자로 쓸 계정 한 분 고르기 (admin → officer → member 순) ──────────
  select p.id, coalesce(nullif(p.name, ''), '새소리단')
    into owner_id, owner_name
    from public.profiles p
   where p.role in ('admin', 'officer', 'member')
   order by case p.role when 'admin' then 1 when 'officer' then 2 else 3 end,
            p.created_at
   limit 1;

  if owner_id is null then
    raise exception '등록자로 쓸 계정을 찾지 못했습니다. 단원 한 분이라도 가입되어 있어야 합니다.';
  end if;

  -- ── 네 건 넣기 (이미 같은 날짜·제목이 있으면 건너뜀) ─────────────────────
  insert into public.events (ev_date, ev_time, title, place, descr, author_id, author_name)
  select v.d::date, '', v.title, v.place, v.descr, owner_id, owner_name
    from (values

      ('2026-11-16',
       '「세대가 함께 그리는 조직문화」 밸런스게임 시작',
       '새소리단 홈페이지 · 밸런스 게임',
       concat_ws(chr(10),
         '새소리단 8기 3조 세대공감팀이 진행하는 밸런스게임이 시작됩니다.',
         '',
         '· 참여 기간 : 11. 16.(월) ~ 11. 26.(목)',
         '· 참여 대상 : 고용노동부 전 직원 (연차·직급·새소리단 여부 무관)',
         '· 걸리는 시간 : 약 1분',
         '· 경품 : 한정판 고드래곤&새초롱이 키캡 · 추첨 50명',
         '· 당첨자 발표 : 11월 말 · 개별 연락',
         '',
         '입직 1년 차 신규 직원부터 수십 년 경력의 선배님까지, 세대마다 다른',
         '생각과 일하는 방식을 함께 들여다봅니다. 정답은 없으니 편하고 솔직하게',
         '골라 주세요!')),

      ('2026-11-23',
       '출근룩 사진 콘테스트 시작',
       '새소리단 홈페이지 · 출근룩 콘테스트',
       concat_ws(chr(10),
         '고용노동부 패셔니스타를 찾아라! 출근룩 사진 콘테스트가 시작됩니다.',
         '',
         '· 참여 기간 : 11. 23.(월) ~ 11. 30.(월)',
         '· 응모 자격 : 고용노동부 직원이면 누구나',
         '',
         '[참여 방법]',
         '1. 사진을 올리고 — 출근룩 한 장 + 한 줄 소개 (한 사람이 한 장)',
         '2. 마음에 드는 출근룩에 좋아요 (한 사람이 한 장에 한 번)',
         '3. 좋아요 많은 순으로 시상 (순위는 실시간으로 바뀝니다)',
         '',
         '[시상 내역]',
         '1등 10만원 1명 / 2등 5만원 2명 / 3등 3만원 3명',
         '장려상 5천원 10명 / 참가상 키캡 추첨 20명',
         '1~3등·장려상은 상품권, 참가상은 키캡으로 드립니다.')),

      ('2026-11-26',
       '「세대가 함께 그리는 조직문화」 밸런스게임 마감',
       '새소리단 홈페이지 · 밸런스 게임',
       concat_ws(chr(10),
         '밸런스게임 참여 마지막 날입니다.',
         '',
         '아직 참여하지 않으셨다면 오늘 안에 참여해 주세요. 약 1분이면 됩니다.',
         '경품은 한정판 고드래곤&새초롱이 키캡이며 추첨 50명, 당첨자는 11월',
         '말에 개별 연락드립니다.',
         '',
         '투표 결과는 카드뉴스로 정리해 우리부 소식과 새소리단 홈페이지에',
         '공유할 예정입니다.')),

      ('2026-11-30',
       '출근룩 사진 콘테스트 마감',
       '새소리단 홈페이지 · 출근룩 콘테스트',
       concat_ws(chr(10),
         '출근룩 사진 콘테스트 마지막 날입니다.',
         '',
         '순위는 좋아요가 많은 순으로 정해집니다.',
         '1등 10만원 1명 / 2등 5만원 2명 / 3등 3만원 3명 / 장려상 5천원 10명,',
         '참여만 해도 추첨 20명께 한정판 고드래곤&새초롱이 키캡을 드립니다.',
         '',
         '아직 올리지 않으셨다면 오늘 안에 출근룩 한 장 올려 주세요!'))

    ) as v(d, title, place, descr)
   where not exists (
     select 1 from public.events e
      where e.ev_date = v.d::date
        and e.title   = v.title);

  get diagnostics added = row_count;
  raise notice '일정 % 건을 넣었습니다. (이미 있던 것은 건너뛰었습니다)', added;
end $$;

-- ── 확인용 — 넣은 일정이 잘 들어갔는지 눈으로 봅니다 ────────────────────────
select to_char(ev_date, 'MM. DD.') as "날짜", title as "행사명", place as "장소", author_name as "등록자"
  from public.events
 where ev_date between date '2026-11-16' and date '2026-11-30'
 order by ev_date;
